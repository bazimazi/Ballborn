import type { HazardDef, PlatformDef, RoomTemplate } from '../types'

const FY = 608

function floor(x: number, w: number, breakable = false): PlatformDef {
  return { x, y: FY, w, h: 150, kind: 'metal', breakable }
}

function plat(
  x: number,
  y: number,
  w: number,
  h = 22,
  kind: PlatformDef['kind'] = 'metal',
  extra: Partial<PlatformDef> = {},
): PlatformDef {
  return { x, y, w, h, kind, ...extra }
}

function lava(x: number, w: number, y = 650, h = 90): HazardDef {
  return { type: 'lava', x, y, w, h, dps: 34 }
}

function room(partial: RoomTemplate): RoomTemplate {
  return partial
}

